/**
 * Writes supabase/seed.sql from seed/data.js. Prices and payment schedules come from the
 * same calculator the API uses (packages/shared), so seeded numbers follow the one rounding rule.
 *
 *   npm run db:seed            regenerate seed.sql
 *   build() is also used by the tests to check seed.sql is up to date.
 */
const fs = require('node:fs');
const path = require('node:path');
const { priceBreakdown, paymentSchedule, expandLines, DEFAULTS } = require('@safiri/shared');
const data = require('./data');

const OUT = path.join(__dirname, '..', 'seed.sql');

// Fixed ids so tests and demos can refer to seeded rows. Prefix (hex) identifies the table.
const PREFIX = {
  user: 'a0', destination: 'a1', agency: 'a2', provider: 'a3', listing: 'a4', package: 'a5',
  booking: 'b0', quote: 'b1', member: 'b2', plan: 'b3', instalment: 'b4', payment: 'b5', txn: 'b6',
  refund: 'b7', payout: 'b8', hold: 'b9',
};
const counters = {};
const idMaps = {};
function id(kind, key) {
  idMaps[kind] = idMaps[kind] || {};
  if (!idMaps[kind][key]) {
    counters[kind] = (counters[kind] || 0) + 1;
    idMaps[kind][key] = `${PREFIX[kind]}000000-0000-4000-8000-${counters[kind].toString(16).padStart(12, '0')}`;
  }
  return idMaps[kind][key];
}

const q = (v) => {
  if (v === null || v === undefined) return 'null';
  if (typeof v === 'number' || typeof v === 'boolean') return String(v);
  return `'${String(v).replace(/'/g, "''")}'`;
};
const json = (v) => `${q(JSON.stringify(v))}::jsonb`;
const textArray = (a) => (a.length ? `array[${a.map(q).join(', ')}]` : `'{}'::text[]`);
const day = (n) => `current_date + ${n}`;
const at = (days, extra = '') => `now() + interval '${days} days${extra ? ' ' + extra : ''}'`;

function insert(table, rows) {
  if (!rows.length) return '';
  const cols = Object.keys(rows[0]);
  const values = rows.map((r) => `  (${cols.map((c) => r[c]).join(', ')})`).join(',\n');
  return `insert into public.${table} (${cols.join(', ')}) values\n${values};\n`;
}

/** Per-person price for a package, using the plan's default margin and fee. */
function packagePrice(pkg) {
  return priceBreakdown({
    items: pkg.items.map(([listingKey, , qty]) => ({ label: listingKey, netKes: data.listings[listingKey].netKes, qty })),
    marginBps: DEFAULTS.AGENCY_MARGIN_BPS,
    feeBps: DEFAULTS.PLATFORM_FEE_BPS,
  });
}

/** Dated booking lines for a package (shared rule: rooms are twin share, drives per day). */
function bookingLines(pkg, startDay, travellers) {
  const items = pkg.items.map(([listingKey, day, qty]) => ({ ref: listingKey, unit: data.listings[listingKey].unit, day, qty }));
  return expandLines(items, travellers).map((l) => ({
    listingKey: l.ref,
    day: startDay + l.dayIndex,
    units: l.units,
    netKes: data.listings[l.ref].netKes * l.perPersonQty * travellers,
  }));
}

function build() {
  for (const k of Object.keys(counters)) delete counters[k];
  for (const k of Object.keys(idMaps)) delete idMaps[k];
  const sql = [];
  sql.push(`-- GENERATED by supabase/seed/generate.js from supabase/seed/data.js. Do not edit by hand:
-- change data.js and run \`npm run db:seed\`. Local development and tests only.
-- Seeded users sign in by email (@safiri.test); locally the codes arrive in Mailpit.
`);

  // Users (auth) for travellers, the agency and every provider owner.
  const allUsers = { ...data.users };
  for (const [key, p] of Object.entries(data.providers)) {
    const n = Object.keys(data.providers).indexOf(key) + 1;
    allUsers[`provider:${key}`] = {
      email: `provider-${n}@safiri.test`, phone: `2547000001${String(n).padStart(2, '0')}`, name: p.name, roles: ['traveller', 'provider'], language: 'en',
    };
  }
  sql.push('-- Users. Empty strings in the token columns avoid a known GoTrue sign-in error for seeded users.');
  sql.push(insert('users', Object.entries(allUsers).map(([key, u]) => ({
    instance_id: q('00000000-0000-0000-0000-000000000000'), id: q(id('user', key)), aud: q('authenticated'),
    role: q('authenticated'), email: q(u.email), email_confirmed_at: 'now()', phone: q(u.phone), phone_confirmed_at: 'now()',
    raw_app_meta_data: json({ provider: 'email', providers: ['email'] }), raw_user_meta_data: json({ language: u.language }),
    confirmation_token: q(''), recovery_token: q(''), email_change_token_new: q(''), email_change: q(''),
    created_at: 'now()', updated_at: 'now()',
  }))).replace('public.users', 'auth.users'));

  sql.push('-- Profiles are created by the on_auth_user_created trigger; add names and roles.');
  for (const [key, u] of Object.entries(allUsers)) {
    sql.push(`update public.profiles set name = ${q(u.name)}, roles = '{${u.roles.join(',')}}', language = ${q(u.language)} where user_id = ${q(id('user', key))};`);
  }
  sql.push('');
  sql.push(insert('consents', Object.keys(data.users).flatMap((key) => ['booking', 'notifications'].map((purpose) => ({
    user_id: q(id('user', key)), purpose: q(purpose), granted_at: 'now()',
  })))));

  sql.push(insert('destinations', Object.entries(data.destinations).map(([key, d]) => ({
    id: q(id('destination', key)), slug: q(d.slug), name: q(d.name), region: q(d.region), lat: d.lat, lng: d.lng,
    summary: q(d.summary), best_time: q(d.bestTime), getting_there: q(d.gettingThere), faq: json(d.faq),
    hero_image: q(d.heroImage), sw: json(d.sw), drive_hours: d.driveHours,
  }))));

  const a = data.agency;
  sql.push(insert('agencies', [{
    id: q(id('agency', a.slug)), owner_id: q(id('user', a.owner)), name: q(a.name), slug: q(a.slug),
    licence_no: q(a.licenceNo), verified_at: 'now()',
  }]));

  sql.push(insert('providers', Object.entries(data.providers).map(([key, p]) => ({
    id: q(id('provider', key)), owner_id: q(id('user', `provider:${key}`)), type: q(p.type), name: q(p.name),
    destination_id: q(id('destination', p.destination)), licence_no: q(p.licenceNo),
    verified_at: p.verified === false ? 'null' : 'now()',
    payout_msisdn: q(allUsers[`provider:${key}`].phone), whatsapp_msisdn: q(allUsers[`provider:${key}`].phone),
  }))));

  sql.push(insert('agency_providers', Object.entries(data.providers).filter(([, p]) => p.verified !== false).map(([key]) => ({
    agency_id: q(id('agency', a.slug)), provider_id: q(id('provider', key)), status: q('active'),
  }))));

  sql.push(insert('listings', Object.entries(data.listings).map(([key, l]) => ({
    id: q(id('listing', key)), provider_id: q(id('provider', l.provider)),
    destination_id: q(id('destination', data.providers[l.provider].destination)),
    kind: q(l.kind), unit: q(l.unit), title: q(l.title), capacity: l.capacity,
  }))));

  sql.push('-- One all-year season per listing; seasonal overrides arrive with the Prices screen (Slice 5).');
  sql.push(insert('listing_prices', Object.entries(data.listings).map(([key, l]) => ({
    listing_id: q(id('listing', key)), season_start: day(-400), season_end: day(400), net_kes: l.netKes,
  }))));

  sql.push(`-- Availability for 90 days back and 180 days ahead.
insert into public.availability (listing_id, date, units_total)
select l.id, d::date, l.capacity
from public.listings l, generate_series(current_date - 90, current_date + 180, interval '1 day') d;
`);

  sql.push(insert('packages', Object.entries(data.packages).map(([key, p]) => ({
    id: q(id('package', key)), agency_id: q(id('agency', a.slug)), destination_id: q(id('destination', p.destination)),
    slug: q(p.slug), title: q(p.title), summary: q(p.summary), nights: p.nights,
    margin_bps: DEFAULTS.AGENCY_MARGIN_BPS, deposit_pct: p.depositPct, instalments: p.instalments,
    final_due_days: DEFAULTS.FINAL_DUE_DAYS, inclusions: textArray(p.inclusions), exclusions: textArray(p.exclusions),
    hero_image: q(data.destinations[p.destination].heroImage), from_price_kes: packagePrice(p).totalKes,
    status: q(p.status || 'published'), published_at: p.status === 'draft' ? 'null' : 'now()',
  }))));

  sql.push(insert('package_items', Object.entries(data.packages).flatMap(([key, p]) => p.items.map(([listingKey, dayNo, qty, startTime]) => ({
    package_id: q(id('package', key)), listing_id: q(id('listing', listingKey)), day: dayNo, qty, start_time: q(startTime || null),
  })))));

  sql.push(buildBookings(allUsers));
  return sql.join('\n');
}

function buildBookings(allUsers) {
  const sql = ['-- Sample bookings, one in every state.'];
  let paymentNo = 0;
  const ledger = [];
  const txn = (key, bookingId, refType, refId, lines) => {
    const txnId = id('txn', key);
    for (const [account, debit, credit] of lines) {
      ledger.push({
        txn_id: q(txnId), account: q(account), debit_kes: debit, credit_kes: credit,
        booking_id: q(bookingId), ref_type: q(refType), ref_id: q(refId), memo: q(key),
      });
    }
  };

  for (const [key, b] of Object.entries(data.bookings)) {
    const pkg = data.packages[b.pkg];
    const price = packagePrice(pkg);
    const total = price.totalKes * b.travellers;
    const bookingId = id('booking', key);
    const quoteId = id('quote', key);
    const phone = allUsers[b.user].phone;
    const lines = bookingLines(pkg, b.startDay, b.travellers);
    const isPaidState = ['confirmed', 'fully_paid', 'completed', 'cancelled'].includes(b.status);

    sql.push(`-- ${b.status}: ${b.ref} ${pkg.slug}`);
    sql.push(insert('quotes', [{
      id: q(quoteId), user_id: q(id('user', b.user)), package_id: q(id('package', b.pkg)),
      start_date: day(b.startDay), end_date: day(b.startDay + pkg.nights), travellers: b.travellers,
      items: json(lines.map((l) => ({ listing_id: id('listing', l.listingKey), date_offset: l.day, units: l.units, net_kes: l.netKes }))),
      breakdown: json({ per_person: price, travellers: b.travellers }),
      per_person_kes: price.totalKes, total_kes: total,
      created_at: at(b.createdDay), expires_at: at(b.createdDay, '15 minutes'),
    }]));

    // Group bookings: members' paid shares, allocated to instalments in order.
    let groupPaid = 0;
    if (b.group) groupPaid = b.group.filter((m) => m.paidDay !== null).length * price.totalKes;
    const plan = paymentSchedule({ totalKes: total, depositPct: pkg.depositPct, instalmentCount: pkg.instalments });
    const amounts = [plan.depositKes, ...plan.instalments];
    const paidSeqs = new Map((b.paid || []).map((p) => [p.seq, p.day]));
    const paidKes = b.group ? groupPaid : amounts.filter((_, seq) => paidSeqs.has(seq)).reduce((s, x) => s + x, 0);

    const holdExpires = b.status === 'held' ? `now() + interval '10 minutes'` : b.status === 'expired' ? at(b.createdDay, '15 minutes') : 'null';
    sql.push(insert('bookings', [{
      id: q(bookingId), ref: q(b.ref), user_id: q(id('user', b.user)), phone: q(phone), package_id: q(id('package', b.pkg)),
      quote_id: q(quoteId), status: q(b.status), start_date: day(b.startDay), end_date: day(b.startDay + pkg.nights),
      travellers: b.travellers, total_kes: total, paid_kes: paidKes, is_group: Boolean(b.group),
      hold_expires_at: holdExpires,
      confirmed_at: isPaidState ? at(b.createdDay, '5 minutes') : 'null',
      fully_paid_at: ['fully_paid', 'completed'].includes(b.status) ? at(Math.max(...(b.paid || [{ day: b.createdDay }]).map((p) => p.day))) : 'null',
      completed_at: b.status === 'completed' ? at(b.startDay + pkg.nights + 1) : 'null',
      cancelled_at: b.status === 'cancelled' ? at(b.cancelledDay) : 'null',
      cancel_reason: b.status === 'cancelled' ? q('Traveller cancelled; full refund under policy') : 'null',
      created_at: at(b.createdDay),
    }]));

    sql.push(insert('booking_items', lines.map((l) => ({
      booking_id: q(bookingId), listing_id: q(id('listing', l.listingKey)),
      provider_id: q(id('provider', data.listings[l.listingKey].provider)), date: day(l.day), units: l.units, net_kes: l.netKes,
      provider_status: q(isPaidState ? 'auto_accepted' : 'pending'), responded_at: isPaidState ? at(b.createdDay, '6 minutes') : 'null',
    }))));

    if (b.status === 'held' || b.status === 'expired') {
      const byListing = new Map();
      for (const l of lines) {
        const cur = byListing.get(l.listingKey) || { first: l.day, last: l.day, units: l.units };
        cur.first = Math.min(cur.first, l.day);
        cur.last = Math.max(cur.last, l.day);
        byListing.set(l.listingKey, cur);
      }
      sql.push(insert('inventory_holds', [...byListing].map(([listingKey, h]) => ({
        id: q(id('hold', `${key}:${listingKey}`)), listing_id: q(id('listing', listingKey)), booking_id: q(bookingId),
        quote_id: q(quoteId), first_date: day(h.first), last_date: day(h.last), units: h.units,
        expires_at: holdExpires, released_at: b.status === 'expired' ? at(b.createdDay, '16 minutes') : 'null',
      }))));
    }

    if (!isPaidState) continue;

    // Payment plan and instalments (created when the deposit is paid).
    const planId = id('plan', key);
    const finalDueDay = b.startDay - DEFAULTS.FINAL_DUE_DAYS;
    const dueDays = amounts.map((_, seq) =>
      seq === 0 ? b.createdDay : b.createdDay + Math.round((seq * (finalDueDay - b.createdDay)) / plan.instalments.length));
    sql.push(insert('payment_plans', [{
      id: q(planId), booking_id: q(bookingId), deposit_kes: plan.depositKes, instalment_count: plan.instalments.length,
      final_due_date: day(finalDueDay), grace_days: 2,
    }]));

    let groupLeft = groupPaid;
    sql.push(insert('instalments', amounts.map((amount, seq) => {
      let paid = 0;
      if (b.group) {
        paid = Math.min(amount, groupLeft);
        groupLeft -= paid;
      } else if (paidSeqs.has(seq)) {
        paid = amount;
      }
      const status = paid === amount ? 'paid' : b.status === 'cancelled' ? 'cancelled' : dueDays[seq] < 0 ? 'overdue' : 'due';
      return {
        id: q(id('instalment', `${key}:${seq}`)), plan_id: q(planId), booking_id: q(bookingId), seq, amount_kes: amount,
        paid_kes: paid, due_date: day(dueDays[seq]), status: q(status),
        paid_at: paid === amount ? at(b.group ? b.createdDay : paidSeqs.get(seq)) : 'null',
      };
    })));

    // Payments: one per paid instalment, or one per paid group share.
    const payments = [];
    if (b.group) {
      sql.push(insert('group_members', b.group.map((m, i) => ({
        id: q(id('member', `${key}:${m.user}`)), booking_id: q(bookingId), user_id: q(id('user', m.user)),
        name: q(allUsers[m.user].name), phone: q(allUsers[m.user].phone), share_kes: price.totalKes,
        paid_kes: m.paidDay !== null ? price.totalKes : 0, invite_code: q(`INV${b.ref.slice(4)}${i}X`),
        is_organiser: m.organiser, status: q(m.paidDay !== null ? 'paid' : 'invited'),
      }))));
      for (const m of b.group.filter((x) => x.paidDay !== null)) {
        payments.push({ key: `${key}:${m.user}`, amount: price.totalKes, dayPaid: m.paidDay, msisdn: allUsers[m.user].phone,
          memberId: id('member', `${key}:${m.user}`), instalmentId: null });
      }
    } else {
      for (const [seq, dayPaid] of paidSeqs) {
        payments.push({ key: `${key}:${seq}`, amount: amounts[seq], dayPaid, msisdn: phone, memberId: null,
          instalmentId: id('instalment', `${key}:${seq}`) });
      }
    }
    sql.push(insert('payments', payments.map((p) => {
      paymentNo += 1;
      const paymentId = id('payment', p.key);
      txn(`payment ${p.key}`, bookingId, 'payment', paymentId, [['client_funds', p.amount, 0], ['traveller_prepayments', 0, p.amount]]);
      return {
        id: q(paymentId), booking_id: q(bookingId), member_id: q(p.memberId), instalment_id: q(p.instalmentId),
        msisdn: q(p.msisdn), amount_kes: p.amount,
        merchant_request_id: q(`seed-mr-${paymentNo}`), checkout_request_id: q(`ws_CO_SEED${String(paymentNo).padStart(6, '0')}`),
        mpesa_receipt: q(`SD${String(paymentNo).padStart(8, '0')}`), status: q('succeeded'), result_code: 0,
        result_desc: q('The service request is processed successfully.'), confirmed_at: at(p.dayPaid, '1 minute'),
        created_at: at(p.dayPaid),
      };
    })));

    if (b.status === 'completed') {
      // Trip done: the prepayment becomes provider, agency and platform money.
      const net = price.netKes * b.travellers;
      const margin = price.marginKes * b.travellers;
      const fee = price.feeKes * b.travellers;
      txn(`recognise ${key}`, bookingId, 'recognise', bookingId, [
        ['traveller_prepayments', total, 0], ['provider_payable', 0, net], ['agency_payable', 0, margin], ['platform_revenue', 0, fee],
      ]);
      const byProvider = new Map();
      for (const l of lines) {
        const prov = data.listings[l.listingKey].provider;
        byProvider.set(prov, (byProvider.get(prov) || 0) + l.netKes);
      }
      sql.push(insert('payouts', [...byProvider].map(([prov, amount]) => {
        const payoutId = id('payout', `${key}:${prov}`);
        txn(`payout ${key}:${prov}`, bookingId, 'payout', payoutId, [['provider_payable', amount, 0], ['client_funds', 0, amount]]);
        return {
          id: q(payoutId), provider_id: q(id('provider', prov)), amount_kes: amount, method: q('mpesa_b2c'),
          msisdn: q(allUsers[`provider:${prov}`].phone), status: q('paid'), conversation_id: q(`AG_SEED_${payoutId.slice(-6)}`),
          period_start: day(b.startDay), period_end: day(b.startDay + pkg.nights), paid_at: at(b.startDay + pkg.nights + 3),
        };
      })));
      sql.push(insert('reviews', [{
        booking_id: q(bookingId), user_id: q(id('user', b.user)), rating: b.review.rating, body: q(b.review.body),
        created_at: at(b.startDay + pkg.nights + 2),
      }]));
    }

    if (b.status === 'cancelled') {
      const refundId = id('refund', key);
      const firstPayment = id('payment', payments[0].key);
      txn(`refund ${key}`, bookingId, 'refund', refundId, [['traveller_prepayments', paidKes, 0], ['client_funds', 0, paidKes]]);
      sql.push(insert('refunds', [{
        id: q(refundId), booking_id: q(bookingId), payment_id: q(firstPayment), amount_kes: paidKes, method: q('mpesa_b2c'),
        msisdn: q(phone), status: q('paid'), reason: q('Cancelled 55 days before travel: 100% refund'),
        conversation_id: q(`AG_SEED_R${refundId.slice(-6)}`), paid_at: at(b.cancelledDay, '2 hours'),
      }]));
    }
  }

  sql.push('-- Ledger: each statement below is one balanced transaction.');
  const byTxn = new Map();
  for (const row of ledger) byTxn.set(row.txn_id, [...(byTxn.get(row.txn_id) || []), row]);
  for (const rows of byTxn.values()) sql.push(insert('ledger_entries', rows).trimEnd());

  sql.push(`
-- Availability counters match the seeded bookings and open holds.
update public.availability a set units_booked = s.units
from (
  select bi.listing_id, bi.date, sum(bi.units)::int as units
  from public.booking_items bi join public.bookings b on b.id = bi.booking_id
  where b.status in ('confirmed', 'fully_paid', 'completed')
  group by bi.listing_id, bi.date
) s
where a.listing_id = s.listing_id and a.date = s.date;

update public.availability a set units_held = s.units
from (
  select h.listing_id, d::date as date, sum(h.units)::int as units
  from public.inventory_holds h, generate_series(h.first_date, h.last_date, interval '1 day') d
  where h.released_at is null and h.expires_at > now()
  group by h.listing_id, d::date
) s
where a.listing_id = s.listing_id and a.date = s.date;
`);

  sql.push(insert('referrals', [{
    owner_id: q(id('user', 'wanjiru')), code: q('WANJIRU5'), discount_kes: 500, max_uses: 10, expires_at: at(180),
  }]));
  return sql.join('\n');
}

if (require.main === module) {
  fs.writeFileSync(OUT, build());
  console.log(`Wrote ${path.relative(process.cwd(), OUT)}`);
}

module.exports = { build, packagePrice, SEED_IDS: () => idMaps };
